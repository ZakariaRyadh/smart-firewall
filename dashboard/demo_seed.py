"""Fill a demo database by running the real pipeline on generated knocks.

    python -m dashboard.demo_seed            # write everything at once
    python -m dashboard.demo_seed --live     # replay knock by knock, for the demo

Everything here is generated by us: normal logins and attacks (attack_sim).
Every IP is from the reserved documentation ranges (192.0.2.x, 198.51.100.x,
203.0.113.x), so screenshots never show a real address.
Per knock it does exactly what the gateway hook will do (see sfw/state.py).
"""
import argparse
import random
import time
from pathlib import Path

import joblib
import pandas as pd

from sfw.attack_sim import START, generate
from sfw.decide import ALLOW, decide
from sfw.rules import BLOCK
from sfw.state import (connect, live_features, log_decision, mark_known,
                       recent_knocks, record_knock, set_meta)

ROOT = Path(__file__).resolve().parents[1]
KNOWN = ["192.0.2.10", "192.0.2.24", "192.0.2.37"]
DAYS = 14
# scenario: episodes in the demo
ATTACKS = {"night_unknown": 4, "vpn_source": 4, "burst": 2, "volume": 1,
           "slow_volume": 1, "slow_known": 2}


def normal_logins(rng, start, days, per_day=(1, 2)):
    """Known IPs logging in at working hours, a few times a day."""
    rows = []
    for d in range(days):
        for ip in KNOWN:
            for _ in range(rng.randint(*per_day)):
                t = start + pd.Timedelta(days=d, hours=rng.randint(9, 17),
                                         minutes=rng.randint(0, 59), seconds=rng.randint(0, 59))
                rows.append({"timestamp": t, "source_ip": ip, "scenario": "normal", "episode": -1})
    return pd.DataFrame(rows)


def doc_ips(df):
    """Swap attack_sim's random new IPs for documentation-range ones."""
    pool = [f"198.51.100.{i}" for i in range(1, 255)] + [f"203.0.113.{i}" for i in range(1, 255)]
    new = [ip for ip in df["source_ip"].unique() if ip not in KNOWN]
    mapping = dict(zip(new, pool))
    df["source_ip"] = df["source_ip"].map(lambda ip: mapping.get(ip, ip))
    return df


def build_timeline(seed):
    rng = random.Random(seed)
    parts = [normal_logins(rng, START, DAYS)]
    for i, (name, n) in enumerate(ATTACKS.items()):
        parts.append(generate(name, n, seed=seed + i, known_ips=KNOWN))
    df = pd.concat(parts, ignore_index=True)
    return doc_ips(df).sort_values("timestamp", kind="stable").reset_index(drop=True)


def seed_history(db, rng):
    """Three weeks of normal logins before the demo, so the known IPs are known."""
    hist = normal_logins(rng, START - pd.Timedelta(days=21), 21)
    for t, ip in zip(hist["timestamp"], hist["source_ip"]):
        now = t.to_pydatetime()
        record_knock(db, ip, now)
        mark_known(db, ip, now)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "data" / "demo.db"))
    ap.add_argument("--model", default=str(ROOT / "models" / "model.joblib"))
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--live", action="store_true", help="replay with delays")
    ap.add_argument("--speed", type=float, default=1.0, help="live replay speed")
    args = ap.parse_args()

    out = Path(args.out)
    for p in (out, Path(f"{out}-wal"), Path(f"{out}-shm")):
        p.unlink(missing_ok=True)  # the demo database is always rebuilt from scratch
    db = connect(str(out))
    set_meta(db, "demo", "1")
    bundle = joblib.load(args.model)
    seed_history(db, random.Random(args.seed))

    timeline = build_timeline(args.seed)
    stopped, prev, counts = set(), None, {}
    for _, row in timeline.iterrows():
        ep = (row["scenario"], row["episode"])
        if ep in stopped:
            continue  # blocked: nftables drops this attacker, its knocks never arrive
        now, ip = row["timestamp"].to_pydatetime(), row["source_ip"]

        if args.live and prev is not None:
            gap = (now - prev).total_seconds()
            time.sleep(min(max(gap, 0.35), 2.2) / args.speed)
        prev = now

        feats = live_features(db, ip, now)
        record_knock(db, ip, now)
        d = decide(bundle, feats, recent_knocks(db, ip, now), now)
        log_decision(db, ip, now, d, feats)
        if d.action == ALLOW:
            mark_known(db, ip, now)
        if d.action == BLOCK and row["scenario"] != "normal":
            stopped.add(ep)
        per = counts.setdefault(row["scenario"], {})
        per[d.action] = per.get(d.action, 0) + 1
        if args.live:
            print(f"{now:%m-%d %H:%M:%S} {ip:15} {row['scenario']:13} {d.action:12} {d.reason}")

    print(f"demo db: {out}")
    for name, per in counts.items():
        print(f"  {name:14} {per}")


if __name__ == "__main__":
    main()
