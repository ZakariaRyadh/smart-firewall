"""Run attack_sim against rules + model. Run from the repo root:

    python -m pipeline.evaluate                  # tuning set
    python -m pipeline.evaluate --set final      # final test set, run it last

Tune thresholds on the tuning set only. Never tune on the final set.
All attacks and the normal history are generated by us (synthetic).
"""
import argparse
from collections import Counter
from pathlib import Path

import joblib
import pandas as pd

from pipeline.train import load_normal
from sfw.attack_sim import SCENARIOS, generate
from sfw.decide import ALLOW, decide
from sfw.features import FEATURES, build_features

ROOT = Path(__file__).resolve().parents[1]
SEEDS = {"tuning": 100, "final": 2026}
EPISODES = 50
WINDOW = pd.Timedelta(minutes=5)


def knock_history(times_by_ip, ip, t):
    """Earlier knocks of one IP in the last 5 min, plus the current one."""
    return [(x, True) for x in times_by_ip[ip] if t - WINDOW <= x <= t]


def decide_rows(bundle, feat, stop_at_first=False):
    """Yield (row, decision) for each row of a feature table, in time order."""
    times_by_ip = {ip: sorted(g["timestamp"]) for ip, g in feat.groupby("source_ip")}
    for _, row in feat.sort_values("timestamp").iterrows():
        t = row["timestamp"]
        d = decide(bundle, row[FEATURES].to_dict(),
                   knock_history(times_by_ip, row["source_ip"], t), t)
        yield row, d
        if stop_at_first and d.action != ALLOW:
            return


def eval_attacks(bundle, history, scenario, seed, known_ips):
    atk = generate(scenario, EPISODES, seed, known_ips)
    both = pd.concat([history, atk], ignore_index=True)
    feat = build_features(both)
    feat = feat[feat["scenario"] == scenario]

    reasons, firsts = Counter(), []
    for _, ep in feat.groupby("episode"):
        for k, (row, d) in enumerate(decide_rows(bundle, ep, stop_at_first=True), 1):
            if d.action != ALLOW:
                reasons[f"{d.reason}:{d.action}"] += 1
                firsts.append(k)
                break
    return len(firsts), EPISODES, reasons, firsts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", choices=SEEDS, default="tuning")
    ap.add_argument("--model", default=str(ROOT / "models" / "model.joblib"))
    args = ap.parse_args()

    bundle = joblib.load(args.model)
    real, synth, _ = load_normal()
    cols = ["timestamp", "source_ip"]
    history = pd.concat([real[cols], synth[cols]], ignore_index=True)
    known_ips = sorted(real["source_ip"].unique())
    seed = SEEDS[args.set]

    print(f"set: {args.set} (seed {seed}), {EPISODES} episodes per scenario")
    print("generated attacks and generated normal data, not real traffic\n")
    for i, name in enumerate(SCENARIOS):
        stopped, total, reasons, firsts = eval_attacks(
            bundle, history, name, seed + i, known_ips)
        first = f", first stop at knock {int(pd.Series(firsts).median())} (median)" if firsts else ""
        print(f"{name:14} {stopped:3}/{total}  {dict(reasons)}{first}")

    # Normal rows, scored with the same model it was trained on: in-sample only.
    flagged = Counter()
    for table in (real, synth):
        feat = build_features(table.reset_index(drop=True))
        for _, d in decide_rows(bundle, feat):
            flagged[d.action] += 1
    print(f"\nnormal rows (in-sample, not held out): {dict(flagged)}")


if __name__ == "__main__":
    main()
